import { mkdir, readFile, writeFile } from 'node:fs/promises';
import sharp from 'sharp';

const root = new URL('../', import.meta.url);
const assets = new URL('public/assets/ui/match-results/', root);
const original = await readFile(new URL('result-banner.png', assets));
// Trim only transparent padding; retain the untouched generated source and alpha.
const { data, info } = await sharp(original).trim().resize({ width: 1440, withoutEnlargement: true })
  .raw().toBuffer({ resolveWithObject: true });
const input = () => sharp(data, { raw: info });
const png = await input().png({ compressionLevel: 9, adaptiveFiltering: true }).toBuffer();
const webp = await input().webp({ lossless: true, effort: 6 }).toBuffer();
const extension = webp.length < png.length ? 'webp' : 'png';
const selected = extension === 'webp' ? webp : png;
await mkdir(new URL('runtime/', assets), { recursive: true });
const file = `runtime/result-banner.${extension}`;
await writeFile(new URL(file, assets), selected);
const backgroundSource = await readFile(new URL('forest-background.png', assets));
// Opaque scenery uses perceptual WebP; the foreground cutout remains lossless.
const background = await sharp(backgroundSource).resize({ width: 1600, withoutEnlargement: true })
  .webp({ quality: 86, effort: 6 }).toBuffer({ resolveWithObject: true });
await writeFile(new URL('runtime/forest-background.webp', assets), background.data);
const titleSource = await readFile(new URL('section-title.png', assets));
const title = await sharp(titleSource).trim().resize({ width: 1000, withoutEnlargement: true })
  .webp({ lossless: true, effort: 6 }).toBuffer({ resolveWithObject: true });
await writeFile(new URL('runtime/section-title.webp', assets), title.data);
await writeFile(new URL('src/ui/matchResultsExports.json', root), JSON.stringify({ title: {
  file: 'runtime/section-title.webp', width: title.info.width, height: title.info.height,
}, background: {
  file: 'runtime/forest-background.webp', width: background.info.width, height: background.info.height,
}, banner: {
  file, width: info.width, height: info.height,
} }, null, 2) + '\n');
await writeFile(new URL('runtime/REPORT.md', assets), '# Match results export\n\n'
  + 'Generated by `node scripts/export-match-results.mjs`. PNG and WebP encode identical resized pixels losslessly.\n\n'
  + `Runtime: ${info.width} × ${info.height}. Original PNG: ${original.length} bytes; optimized PNG: ${png.length}; lossless WebP: ${webp.length}.\n\n`
  + `Selected ${extension}: ${selected.length} bytes (${(100 * (1 - selected.length / original.length)).toFixed(1)}% smaller).\n\n`
  + `Opaque forest background: ${backgroundSource.length} → ${background.data.length} bytes; WebP quality 86, ${background.info.width} × ${background.info.height}.\n\n`
  + `Section title: ${titleSource.length} → ${title.data.length} bytes; lossless WebP, ${title.info.width} × ${title.info.height}.\n`);
console.log(`${original.length} → ${selected.length} bytes (${extension}); ${info.width} × ${info.height}`);
