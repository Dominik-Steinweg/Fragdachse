import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = new URL('../', import.meta.url);
const assets = new URL('public/assets/ui/lobby-forest/', root);
// Always export from the untouched generated PNGs. Crops are in original pixels.
// Output dimensions include headroom; never resize an already exported image.
const config = {
  frame: { file: 'frame', size: [1062, 1482], output: [1062, 1482] }, // 596x832 card, 2x cache: keep all source detail
  wood: { file: 'wood', size: [1254, 1254], output: [896, 896] }, // 438.9px repeat; >2x sampling
  buttonFrame: { file: 'button-frame', size: [2172, 724], crop: [15, 177, 2141, 366], output: [536, 92] }, // 8px caps: 32px source caps
  leaves: { file: 'leaves', size: [1254, 1254], output: [128, 128] }, // 40x40 popup ornament, >3x reserve
  medallion: { file: 'medallion', size: [1254, 1254], output: [320, 320] }, // 140x140, 2x cache + reserve
  relief: { file: 'relief', size: [1536, 1024], crop: [18, 189, 1504, 656], output: [940, 410] }, // 460x200.64, 2x cache
  ready: { file: 'ready', size: [2172, 724], crop: [21, 217, 2129, 288], output: [1065, 144] }, // 484x65.47 within 484x80, >2x + hover
  world: { file: 'world', size: [2073, 758], crop: [24, 72, 2015, 569], output: [640, 181] }, // 280x79.07 within 280x80, >2x + hover
};

await mkdir(new URL('runtime/', assets), { recursive: true });
const manifest = {};
const rows = [];
for (const [name, spec] of Object.entries(config)) {
  const original = await readFile(new URL(`${spec.file}.png`, assets));
  const metadata = await sharp(original).metadata();
  if (metadata.width !== spec.size[0] || metadata.height !== spec.size[1]) {
    throw new Error(`${spec.file}: source dimensions changed; review crop and output in scripts/export-lobby-forest.mjs`);
  }
  const [left, top, width, height] = spec.crop ?? [0, 0, ...spec.size];
  const [outWidth, outHeight] = spec.output;
  if (outWidth > width || outHeight > height) throw new Error(`${name}: avoid upscaling`);
  const { data, info } = await sharp(original)
    .extract({ left, top, width, height })
    .resize(outWidth, outHeight, { fit: 'fill', kernel: 'lanczos3' })
    .raw().toBuffer({ resolveWithObject: true });
  const input = () => sharp(data, { raw: info });
  const png = await input().png({ compressionLevel: 9, adaptiveFiltering: true, palette: false }).toBuffer();
  const webp = await input().webp({ lossless: true, effort: 6 }).toBuffer();
  const extension = webp.length < png.length ? 'webp' : 'png';
  const selected = extension === 'webp' ? webp : png;
  const file = `runtime/${spec.file}.${extension}`;
  await writeFile(new URL(file, assets), selected);
  // Reference dimensions retain exact proportions/repeat lengths despite integer export rounding.
  manifest[name] = { file, width: outWidth, height: outHeight, sourceWidth: width, sourceHeight: height };
  rows.push({ asset: name, before: `${metadata.width}×${metadata.height}`, after: `${outWidth}×${outHeight}`,
    original: original.length, png: png.length, webp: webp.length, selected: extension });
}
await writeFile(new URL('src/ui/lobbyForestExports.json', root), JSON.stringify(manifest, null, 2) + '\n');
const total = key => rows.reduce((sum, row) => sum + row[key], 0);
const selectedTotal = rows.reduce((sum, row) => sum + row[row.selected], 0);
const report = '# Lobby forest export comparison\n\nGenerated by `npm run assets:lobby-forest` with sharp ' + sharp.versions.sharp
  + '. Sizes in bytes; PNG and WebP use the same resized pixels. Both encodings are lossless.\n\n'
  + '| Asset | Original pixels | Runtime pixels | Original PNG | Optimized PNG | Lossless WebP | Selected |\n'
  + '| --- | --- | --- | ---: | ---: | ---: | --- |\n'
  + rows.map(row => `| ${row.asset} | ${row.before} | ${row.after} | ${row.original} | ${row.png} | ${row.webp} | ${row.selected} |`).join('\n')
  + `\n\nTotal: ${total('original')} → ${selectedTotal} bytes (${(100 * (1 - selectedTotal / total('original'))).toFixed(1)}% smaller).\n`;
await writeFile(new URL('runtime/REPORT.md', assets), report);
console.table(rows);
console.log(`${total('original')} → ${selectedTotal} bytes. Manifest: ${fileURLToPath(new URL('src/ui/lobbyForestExports.json', root))}`);
